#!/bin/sh
# build-9k10t1.sh — build the 06-09 tier venue kernel (G-06-1; the
# Harvey-kernel amd64 tier venue, maintainer direction 2026-11-05).
#
# Builds TWO kernels via the linux private-namespace path
# (sys/src/RUN_BUILD_IN_PRIVATE_NAMESPACE — unshare -m; the same
# machinery `nix run .#build` uses):
#   1. 9k10cpu — re-proof that the sacred amd64 kernel still compiles
#      and links against the raised devroot.c (Nbootfiles 32 -> 64);
#   2. 9k10t1  — the venue kernel: k10cpu's device set verbatim with the
#      43-file tier embed (the amd64 tier-1 read-only set + the D-10
#      sweep + sentinel + nm-input) baked into devroot, grown by 15-02
#      (USPACE-07) with the services-sweep embed — the sweep + the
#      tier-2-built services binaries + the tcpNNNN listener service
#      programs (58 embedded files total this plan).
# The build is nuke-sandwiched (build/scripts/build:50-52's shape:
# `mk nuke && mk … && mk nuke`) because the k10 build products
# (k10t1.c, k10t1.root.s, 9k10t1{,.elf}, 9k10cpu{,.elf}, errstr.h,
# init.h, init.out, amd64l.h, sipi.h) are NOT gitignored and the
# plan-level gate is a clean `git status`; systab.c is regenerated by
# portmkfile on every 9k build and unreachable by the nuke, so it (plus
# k10t1.c and the transient .tier1-stage/) rides .gitignore instead.
#
# 14-08 (XEXEC-04) extends the venue script additively, twice:
#   - the passwordless venue (the 14-05 discipline): when the host
#     grants no passwordless sudo, the SAME build-steps core runs
#     inside the unprivileged user+mount namespace's tmpfs chroot
#     scaffold (build/x86_64/stage-build.sh's proven shape) instead of
#     RUN_BUILD_IN_PRIVATE_NAMESPACE — the nuke sandwich, asserts, and
#     products are identical, only the namespace entry differs.
#   - the r9-x64 execution leg: after the 9k build, the tier binary
#     set BOTH venues consume (/amd64/bin — this kernel's embed source
#     AND the r9 tier image's staging home) is asserted complete and
#     pinned to .build/9k10t1-tier-manifest.sha256; mkimage.sh's tier
#     bake verifies against it — the identical-6.outs ABI witness
#     (D-01's both-kernels consequence, T-14-15) made structural.
#
# Usage (from the repo root, inside the nix devshell):
#   nix develop -c sh build/mm/build-9k10t1.sh
# darwin (the namespace build is linux-only — run it in the lima guest):
#   limactl shell harvey -- sh -lc 'cd <repo> && nix develop -c sh build/mm/build-9k10t1.sh'
#
# Env overrides:
#   HARVEY   repo root (default: $PWD)
#
# Exit: 0 iff both kernels built, the venue kernel embeds exactly 58
# root files (the 15-02 services growth), amd64/9k10t1.elf landed, the
# k10 tree is git-clean after the trailing nuke, and the r9 leg's
# tier-set manifest is written.

set -eu

HARVEY="${HARVEY:-$PWD}"

err() { echo "error: $*" >&2; exit 1; }

# --- platform gate: the namespace build is linux-only (unshare -m) ----
if [ "$(uname -s)" != "Linux" ]; then
	echo "error: the private-namespace build is linux-only (RUN_BUILD_IN_PRIVATE_NAMESPACE uses unshare -m)." >&2
	echo "on darwin, run it in the lima guest:" >&2
	echo "  limactl shell harvey -- sh -lc 'cd $HARVEY && nix develop -c sh build/mm/build-9k10t1.sh'" >&2
	exit 2
fi

# --- preconditions (named remediation, never assumed) ------------------
[ -d "$HARVEY/sys/src" ] || err "$HARVEY does not look like the harvey checkout (missing sys/src)"
_missing=""
for b in rc awk nm bind echo; do
	[ -f "$HARVEY/amd64/bin/$b" ] || _missing="$_missing amd64/bin/$b"
done
[ -f "$HARVEY/amd64/lib/libc.a" ] || _missing="$_missing amd64/lib/libc.a"
[ -z "$_missing" ] || err "the embedded set is incomplete:$_missing — run 'nix run .#build' first (populates amd64/bin + amd64/lib)"
_ha=$(uname -m); [ "$_ha" = "arm64" ] && _ha=aarch64
NS_HBIN="$HARVEY/.build/hostbin-linux-$_ha/bin"
for t in 6c 6l 6a; do
	[ -x "$NS_HBIN/$t" ] || err "$NS_HBIN/$t missing — run 'nix run .#setup && nix run .#toolchain' first"
done
# sudo: only the passwordless-sudo venue needs it (the 14-08 userns
# venue below runs unprivileged); checked at the venue split
[ -n "${PLAN9:-}" ] && [ -x "$PLAN9/bin/rc" ] || err "\$PLAN9/bin/rc missing — run inside the nix devshell (nix develop)"

# 15-02: the phase build-tree lock — the kernel build embeds from the
# untracked /amd64 tree and the same-wave tier drivers (15-04's
# subset-build runs) hold this SAME lock for their whole runs (the
# 15-01 coupling contract), so embed harvests and tier builds can never
# interleave.  Held from here (before the embed staging reads /amd64)
# to exit.
command -v flock >/dev/null 2>&1 || err "flock not found — the amd64 build-tree lock needs util-linux flock"
exec 9>"$HARVEY/.build/amd64-tree.lock"
flock 9 || err "cannot acquire the amd64 build-tree lock"
echo "== amd64 build-tree lock held: $HARVEY/.build/amd64-tree.lock"

# the 06-02 idiom (D-02): the log greps below use -q/-E, which plan9
# grep lacks — resolve a host grep once (never rely on PATH ordering
# against the devshell's plan9port tail)
GREP=$(command -v /usr/bin/grep || command -v grep) || err "no host grep found"
export GREP  # the namespace script greps the generated k10t1.c — the
             # buildnamespace export-dump only carries exported vars

# --- staging (idempotent): the sweep, sentinel, and nm-input ride ------
# the embedded root from a transient staging dir (single-sourced in
# build/aarch64/; .tier1-stage is gitignored, never committed).
STAGE="$HARVEY/sys/src/9k/k10/.tier1-stage"
rm -rf "$STAGE"
mkdir -p "$STAGE"
cp "$HARVEY/build/aarch64/tier1-sweep.rc" "$STAGE/tier1-sweep.rc"
cp "$HARVEY/build/aarch64/nm-input.7" "$STAGE/nm-input.7"
# rc and echo embed under TWO names each (hrc+rc for the sweep's $B/h*
# vocabulary AND the shebang's /boot/rc; hecho+echo likewise) — but
# parse keys each rootdir entry's C symbol name off the SOURCE path, so
# the second name needs its own staged copy (the same source twice
# duplicates _amd64_bin_rc{code,len}/_amd64_bin_echo{code,len} and the
# 6l link fails with 'multiple initialization' — measured on the first
# venue build 2026-11-05).
cp "$HARVEY/amd64/bin/rc" "$STAGE/rc"
cp "$HARVEY/amd64/bin/echo" "$STAGE/echo"
# the byte-exact sentinel from subset-exec.sh:308 — assert its digests
# equal the sweep's pinned constants so a drifted fixture reds at BUILD
# time, never in the guest.
printf 'alpha bravo charlie\n__SUBSET_GREP_LINE__\n' > "$STAGE/sentinel.txt"
_md5=$(md5sum "$STAGE/sentinel.txt" | awk '{print $1}')
_sha1=$(sha1sum "$STAGE/sentinel.txt" | awk '{print $1}')
[ "$_md5" = "6c3d57e94871f9606c5b63c315e76135" ] || err "sentinel md5 drift: $_md5 (want 6c3d57e94871f9606c5b63c315e76135) — tier1-sweep.rc's pinned assert would red in the guest"
[ "$_sha1" = "893404a2c36b54f5c7874070d1acefe38f7ce652" ] || err "sentinel sha1 drift: $_sha1 (want 893404a2c36b54f5c7874070d1acefe38f7ce652)"
echo "== staged: tier1-sweep.rc + nm-input.7 + sentinel.txt (digests pinned)"

# --- 15-02 (USPACE-07): the services-sweep embed members ---------------
# The donor venue's services leg: the committed sweep + the tier-2-built
# /amd64/bin binaries it probes (the ONE build both venues consume —
# run sh build/x86_64/subset-build.sh first).  Staged copies carry the
# h* sweep vocabulary (the $B/h* idiom); the tcpNNNN members are the
# listener's per-connection SERVICE programs (listen.c execs
# servdir/<proto><port> — the staged-copy trick again: parse keys each
# rootdir entry's C symbol name off the SOURCE path, so a second embed
# NAME for the same source needs its own staged file, like rc/echo).
SVC_SWEEP="$HARVEY/build/x86_64/services-sweep.rc"
[ -f "$SVC_SWEEP" ] || err "services sweep missing: $SVC_SWEEP"
cp "$SVC_SWEEP" "$STAGE/services-sweep.rc"
svc_copy() {
	[ -f "$HARVEY/$1" ] || err "services embed member missing: $HARVEY/$1 — run 'sh build/x86_64/subset-build.sh' first (the tier-2 build)"
	cp "$HARVEY/$1" "$STAGE/$2"
	magic=$(od -An -tx1 -N4 "$STAGE/$2" | tr -d ' \n')
	[ "$magic" = "00008a97" ] || err "services embed member $2: bad magic $magic (want 00008a97 — amd64 S_MAGIC)"
}
svc_copy amd64/bin/mntgen hmntgen
svc_copy amd64/bin/ndb/cs hcs
svc_copy amd64/bin/ndb/csquery hcsquery
svc_copy amd64/bin/ndb/dns hdns
svc_copy amd64/bin/ndb/dnsquery hdnsquery
svc_copy amd64/bin/exportfs hexportfs
svc_copy amd64/bin/srv hsrv
svc_copy amd64/bin/listen hlisten
# tcp9901/tcp9902: the listener's per-connection SERVICE programs
# (listen.c execes servdir/<proto><port>) — echo and authsrv under
# their service names, the staged-copy trick (parse keys C symbols off
# the SOURCE path)
svc_copy amd64/bin/echo tcp9901
svc_copy amd64/bin/auth/authsrv tcp9902
# hsvctcpecho: the sweep's one-shot tcp client — built HOST-SIDE link-
# only (the nm-input.6 discipline: 6c with relative -I paths from the
# repo root, 6l with -L to the checkout's amd64/lib for the libc
# autolib), like the tier-1 fixture object but linked.
(	cd "$HARVEY" && \
	"$NS_HBIN/6c" -FTVw -o "$STAGE/svctcpecho" -Isys/include -Iamd64/include build/x86_64/svctcpecho.c && \
	"$NS_HBIN/6l" -o "$STAGE/hsvctcpecho" -L "$HARVEY/amd64/lib" "$STAGE/svctcpecho" && \
	rm -f "$STAGE/svctcpecho"
) || err "hsvctcpecho host-side build failed"
magic=$(od -An -tx1 -N4 "$STAGE/hsvctcpecho" | tr -d ' \n')
[ "$magic" = "00008a97" ] || err "hsvctcpecho: bad magic $magic (want 00008a97)"
# 15-02 Task 3 (the D-08 auth subset): factotum (tier-1-built) + keyfs
# (tier-2), and hmkdir — the keyfs probe's DMDIR-create client, built
# host-side link-only the same way (mkdir is not a tier member on x64 —
# the write-flow class — so the venue builds its one embed copy here)
svc_copy amd64/bin/auth/factotum hfactotum
svc_copy amd64/bin/auth/keyfs hkeyfs
(	cd "$HARVEY" && \
	"$NS_HBIN/6c" -FTVw -o "$STAGE/mkdir" -Isys/include -Iamd64/include sys/src/cmd/mkdir.c && \
	"$NS_HBIN/6l" -o "$STAGE/hmkdir" -L "$HARVEY/amd64/lib" "$STAGE/mkdir" && \
	rm -f "$STAGE/mkdir"
) || err "hmkdir host-side build failed"
magic=$(od -An -tx1 -N4 "$STAGE/hmkdir" | tr -d ' \n')
[ "$magic" = "00008a97" ] || err "hmkdir: bad magic $magic (want 00008a97)"
echo "== staged: services-sweep.rc + 14 services members (magic-checked)"

# the nvram rootdir stub (build/scripts/build:48-49's rule, host-side):
# k10cpu's rootdir names ../root/nvram, which the full in-OS build
# creates as a 512-byte zero file — on a host where only the subset
# drivers ran (never `nix run .#build`), the stub is absent and mk dies
# "don't know how to make '../root/nvram'".  head (never shadowed by
# hostbin — Plan 9 dd's dash-pair syntax is; the D-02 class) emits the
# same 512 zero bytes.  gitignored (the same rule the full build's
# artifact rides).
if [ ! -f "$HARVEY/sys/src/9k/root/nvram" ]; then
	head -c 512 /dev/zero > "$HARVEY/sys/src/9k/root/nvram" || err "cannot write the nvram stub"
	echo "== staged: sys/src/9k/root/nvram stub (512 zero bytes)"
fi

# --- the namespace build (nuke sandwich) --------------------------------
# NS_HBIN is computed host-side above and EXPORTED into the namespace —
# never read HARVEY_LINUX_BIN from the environment (the gethunk override
# lesson: a caller's override silently retargets the toolchain).
export NS_HBIN
LOG="$HARVEY/.build/build-9k10t1.log"
mkdir -p "$HARVEY/.build"
# 14-08: the build-steps CORE, shared verbatim by BOTH namespace venues
# (the passwordless split below) — everything from the k10 cd through
# the trailing nuke; each venue's wrapper only sets the environment
# (PATH shape, FORCERCFORMK) and runs this file.
CORE="$(mktemp "${TMPDIR:-/tmp}/ns-9k10t1-core.XXXXXX.sh")"
cat > "$CORE" <<'EOF'
cd /sys/src/9k/k10 || exit 1
fails=0
# leading nuke: clean slate (portmkfile's nuke chain removes *.root.[cs],
# *.out, errstr.h, init.h, all k10*.c, all [9bz]k10* kernels, amd64l.h,
# sipi.h)
mk nuke || fails=1
# the devroot raise's compile re-proof of the sacred amd64 kernel: its
# objects recompile and it relinks against the new devroot.6
if [ "$fails" -eq 0 ]; then mk CONF=k10cpu 9k10cpu || fails=1; fi
# the venue kernel
if [ "$fails" -eq 0 ]; then mk CONF=k10t1 9k10t1 || fails=1; fi
# in-tree product asserts
if [ "$fails" -eq 0 ]; then
	[ -s 9k10t1 ] || { echo "error: 9k10t1 missing/empty" >&2; fails=1; }
	[ -s 9k10t1.elf ] || { echo "error: 9k10t1.elf missing/empty" >&2; fails=1; }
fi
# the embedded-count assert: parse emits exactly one addbootfile line
# per rootdir entry into the generated k10t1.c, so this counts what the
# kernel actually embeds.  MUST run here — the trailing nuke removes
# k10t1.c.  (mkrootall prints no count and mk echoes the embed recipe as
# one logical recipe, so log-line counting is unsound.)
if [ "$fails" -eq 0 ]; then
	N=$("$GREP" -c 'addbootfile("' k10t1.c)
	echo "embedded root files: $N"
	[ "$N" = 58 ] || { echo "error: embedded root file count $N != 58 (devroot.c's panic ceiling is 64; a missing stage file fails mk's prerequisite check first)" >&2; fails=1; }
fi
# land the venue kernel in /amd64 (inside the namespace the repo root is
# /; host-side that is $HARVEY/amd64/9k10t1.elf — gitignored via the
# existing amd64/9* pattern)
if [ "$fails" -eq 0 ]; then
	cp 9k10t1.elf /amd64/9k10t1.elf || fails=1
	ls -l 9k10cpu.elf 9k10t1.elf /amd64/9k10t1.elf
fi
# trailing nuke REGARDLESS of assert outcome (the in-tree products
# vanish; the /amd64 copy survives — nuke never touches /amd64)
mk nuke || fails=1
exit "$fails"
EOF

# venue split (the 14-05 discipline, carried by build/x86_64's drivers):
# passwordless sudo → the documented RUN_BUILD_IN_PRIVATE_NAMESPACE
# path (real root, the su drop, the buildnamespace export-dump);
# otherwise the unprivileged user+mount namespace with the tmpfs chroot
# scaffold (same binds, no privilege, same uid — the artifacts land
# owned right).  The build steps, asserts, and products are IDENTICAL —
# only the namespace entry differs.
set +e
if sudo -n true 2>/dev/null; then
	# /bin/rc guard (the gethunk fix's runner finding; SUDO venue only —
	# the namespace here is the host root plus binds, so mk's
	# FORCERCFORMK recipes exec the HOST /bin/rc): mk's recipes exec
	# /bin/rc inside the namespace.
	[ -x /bin/rc ] || sudo cp "$PLAN9/bin/rc" /bin/rc
	NSK="$(mktemp "${TMPDIR:-/tmp}/ns-9k10t1.XXXXXX.sh")"
	# The wrapper is bash (NS_TARGET="bash …") carrying the namespace-
	# proven line shape: buildnamespace is RUN_BUILD_IN_PRIVATE_
	# NAMESPACE's own `export`-dump, sourced to restore the captured
	# environment.  The /rc/bin:. tail is load-bearing (the phase-01
	# namespace-env rule — the proven nix/build.sh:28-30 shape): inside
	# the namespace /rc is the repo's rc/ bind, and bootmkfile's
	# archive rule execs `membername` from rc/bin; without the tail the
	# BOOTLIB archive silently builds EMPTY and the boot$CONF.out link
	# fails with undefined boot/connecttcp.
	cat > "$NSK" <<EOF
cd /sys/src || exit 1
. buildnamespace
PATH="$NS_HBIN:\$PATH:/rc/bin:."
export PATH
export FORCERCFORMK=1
bash $CORE
EOF
	echo "== namespace build (sudo unshare): mk nuke && mk CONF=k10cpu 9k10cpu && mk CONF=k10t1 9k10t1 && mk nuke"
	echo "== build log: $LOG (tail -f to follow)"
	(cd "$HARVEY/sys/src" && NS_TARGET="bash $NSK" bash RUN_BUILD_IN_PRIVATE_NAMESPACE) > "$LOG" 2>&1
	NSRC=$?
	rm -f "$NSK"
else
	# The chroot scaffold for the passwordless venue (unshare -Ur -m):
	# build/x86_64/stage-build.sh's proven shape, carried verbatim in
	# spirit — the tmpfs owns everything (never rm'd; dies with the
	# namespace), leaf binds only, /bin a usrmerge symlink farm + the
	# plan9port rc bind, the per-arch dirs bound (libmach's absolute
	# /$objtype/include includes), /unix for the host-toolchain mkfile.
	# No cleanup trap — the tmpfs IS the cleanup (an rm -rf would walk
	# THROUGH the bind mounts into the source trees).
	TMPD="$(mktemp -d "${TMPDIR:-/tmp}/ns-9k10t1-scaffold.XXXXXX")"
	cat > "$TMPD/ns-9k10t1-userns.sh" <<'USERNS_EOF'
#!/usr/bin/env bash
# ns-9k10t1-userns.sh — the passwordless venue's namespace side: the
# tmpfs chroot scaffold + the shared build core.  Never committed;
# regenerated each run.
set -e
NSX=$(mktemp -d "${TMPDIR:-/tmp}/ns-9k10t1-root.XXXXXX")
mount -t tmpfs tmpfs "$NSX"

mkdir -p "$NSX"/{sys,amd64,rc,lib,etc,tmp,harvey,unix,nix/store,run,dev,usr,bin}
mount --bind "$HARVEY_SYS" "$NSX/sys"
mount --bind "$HARVEY_AMD64" "$NSX/amd64"
mount --bind "$HARVEY_RC" "$NSX/rc"
# /lib: the 9k kernel build consumes /lib/keyboard (portmkfile:82-83's
# mklatinkbd -> ../port/latin1.h rule).  The sudo venue builds a MERGED
# /lib (BUILD_SETUP_NAMESPACE: the distro loader must stay reachable);
# in THIS chroot every binary's interpreter is a nix-store absolute
# path (bound above), so a plain bind of the repo's lib/ is safe.
mount --bind "$HARVEY_LIB" "$NSX/lib"
mount --bind "$HARVEY_UNIX" "$NSX/unix"
for a in 386 aarch64 arm mips mips64 power power64 riscv riscv64 sparc acme; do
	mkdir -p "$NSX/$a"
	mount --bind "$HARVEY_REAL/$a" "$NSX/$a"
done
mount --bind /etc "$NSX/etc"
mount --bind /tmp "$NSX/tmp"
mount --bind "$HARVEY_REAL" "$NSX/harvey"
mount --bind /nix/store "$NSX/nix/store"
ln -sfn "$(readlink /run/current-system)" "$NSX/run/current-system"
ln -sfn ../run/current-system/sw/bin "$NSX/usr/bin"
for b in sh bash env cp mv rm ls cat mkdir touch sed grep find od tr; do
	ln -sfn "../run/current-system/sw/bin/$b" "$NSX/bin/$b"
done
for d in null zero urandom random; do
	touch "$NSX/dev/$d"
	mount --bind "/dev/$d" "$NSX/dev/$d"
done
touch "$NSX/bin/rc"
mount --bind "$PLAN9/bin/rc" "$NSX/bin/rc"

export HARVEY=/harvey
INNER_BIN="/harvey${HARVEY_LINUX_BIN#"$HARVEY_REAL"}"
# the core's env (the sudo venue's wrapper equivalents): hostbin FIRST,
# the /rc/bin:. tail load-bearing (membername), FORCERCFORMK for mk.
exec chroot "$NSX" /usr/bin/env \
	HARVEY=/harvey \
	HARVEY_LINUX_BIN="$INNER_BIN" \
	PLAN9="$PLAN9" \
	GREP="$GREP" \
	PATH="$INNER_BIN:/rc/bin:$PATH:." \
	HOME="$HOME" \
	FORCERCFORMK=1 CGO_ENABLED=0 objtype=amd64 cputype=unix \
	bash "$1"
USERNS_EOF
	echo "== no passwordless sudo — namespace build in an unprivileged user namespace (unshare -Ur -m chroot scaffold): mk nuke && mk CONF=k10cpu 9k10cpu && mk CONF=k10t1 9k10t1 && mk nuke"
	echo "== build log: $LOG (tail -f to follow)"
	HARVEY_SYS="$HARVEY/sys" HARVEY_AMD64="$HARVEY/amd64" HARVEY_RC="$HARVEY/rc" HARVEY_LIB="$HARVEY/lib" \
	HARVEY_UNIX="$HARVEY/unix" HARVEY_REAL="$HARVEY" HARVEY_LINUX_BIN="$HARVEY_LINUX_BIN" \
	PATH="$HARVEY_LINUX_BIN:$PATH" \
	unshare -Ur -m bash "$TMPD/ns-9k10t1-userns.sh" "$CORE" > "$LOG" 2>&1
	NSRC=$?
	rm -rf "$TMPD"
fi
set -e
rm -f "$CORE"
# mk exit status is never enough on its own (02-12) — check the harness
# status AND the product asserts below.
[ "$NSRC" -eq 0 ] || {
	echo "error: the namespace build failed (rc=$NSRC) — last 40 lines of $LOG:" >&2
	tail -40 "$LOG" >&2
	exit 1
}

# --- host-side product asserts ------------------------------------------
if [ ! -s "$HARVEY/amd64/9k10t1.elf" ]; then
	echo "error: amd64/9k10t1.elf missing/empty after the namespace build — last 40 lines of $LOG:" >&2
	tail -40 "$LOG" >&2
	exit 1
fi
# the embedded-count line must be exactly 58 (the 43-entry tier-1 venue
# embed + the 15-02 services-sweep members (58); re-asserted host-side from
# the captured log — the in-namespace assert is the primary; this is the
# driver's own record)
if ! "$GREP" -q '^embedded root files: 58' "$LOG"; then
	echo "error: the build log lacks 'embedded root files: 58' — the venue embed count is wrong; last 40 lines:" >&2
	tail -40 "$LOG" >&2
	exit 1
fi
# the trailing nuke's proof: no unignored k10 intermediates survive
# (systab.c — regenerated by portmkfile:85-86 on every 9k build and
# unreachable by the nuke — rides the .gitignore rule, as do k10t1.c and
# .tier1-stage/; anything else reds HERE at build time, not later)
_dirty=$(git -C "$HARVEY" status --porcelain -- sys/src/9k)
if [ -n "$_dirty" ]; then
	echo "error: sys/src/9k is not git-clean after the nuke sandwich:" >&2
	echo "$_dirty" >&2
	exit 1
fi

# success: surface the key evidence lines from the captured log
"$GREP" -E '^embedded root files: |9k10(t1|cpu)\.elf' "$LOG" | tail -6 || true
echo "== build-9k10t1 OK: amd64/9k10t1.elf ($(wc -c < "$HARVEY/amd64/9k10t1.elf" | tr -d ' ') bytes), 9k10cpu relinked against devroot(Nbootfiles=64), k10 tree git-clean"

# --- the r9-x64 execution leg (14-08, XEXEC-04): ONE binary set, TWO
#     venues.  The kernel above just embedded /amd64/bin's tier set;
#     the r9 tier image stages the SAME set (mkimage.sh's tier bake
#     verifies every digest against the manifest written here — the
#     identical-6.outs ABI witness, T-14-15, is structural: a drifted
#     member between the two builds reds the BAKE, not the eye).  The
#     member list is computed from the x64 tier data (the same
#     entry->name mapping the venue gates' expectations use), plus
#     bind — the embed's bare-name boot-plumbing member subset-build
#     installs outside the tier data (insertion-only, the aarch64
#     driver's 07-07 shape).
R9_MANIFEST="$HARVEY/.build/9k10t1-tier-manifest.sha256"
R9_RELS=$(
	awk 'NF && $1 !~ /^#/ { print $1 }' "$HARVEY/build/x86_64/tiers/tier1-cmds.txt" |
	while read -r e; do
		case "$e" in
		9k/boot|stage/*|cmd/paqfs:paqfs|cmd/cc) continue ;;
		esac
